var (
	mergedCertPool *x509.CertPool
	poolOnce       sync.Once
)

// GetUpstreamCertPool returns the system cert pool combined with bundled GlobalSign root CAs.
func GetUpstreamCertPool() *x509.CertPool {
	poolOnce.Do(func() {
		pool, err := x509.SystemCertPool()
		if err != nil || pool == nil {
			pool = x509.NewCertPool()
		}
		pool.AppendCertsFromPEM([]byte(globalSignRootsPEM))
		mergedCertPool = pool
	})
	return mergedCertPool
}
